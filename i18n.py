def init_app(app) -> None:
    """Register i18n hooks on a Flask app."""

    @app.before_request
    def _i18n_before_request():
        # Touching get_locale() before_request is enough to apply session
        # precedence; we also pre-set the session language if the URL carries
        # ?lang= so the user can switch without a separate redirect.
        requested = (request.args.get("lang") or "").lower()
        if _is_valid_locale(requested):
            session["lang"] = requested

    @app.context_processor
    def _i18n_context():
        return {
            "t": t,
            "locale": get_locale(),
            "locales": LOCALES,
            "locale_names": LOCALE_NAMES,
            "locale_flags": LOCALE_FLAGS,
            "current_locale": get_locale(),
            "catalog": catalog(),
            "format_currency": format_currency,
            "format_date": format_date,
        }

    @app.template_filter("t")
    def _t_filter(key, **kwargs):
        return t(key, **kwargs)

    @app.route("/api/i18n/<locale>")
    def _api_i18n(locale: str):
        if not _is_valid_locale(locale):
            return jsonify({"error": "unsupported locale"}), 400
        return jsonify({
            "locale": locale,
            "messages": catalog(locale),
            "names": LOCALE_NAMES,
            "flags": LOCALE_FLAGS,
        })

    @app.route("/set-language/<locale>")
    def _set_language(locale: str):
        if not _is_valid_locale(locale):
            return redirect(request.referrer or url_for("index"))
        set_locale(locale)
        target = request.referrer or url_for("index")
        # Avoid redirect loop if referrer is on /set-language itself
        if "/set-language/" in target or "/set-theme/" in target:
            target = url_for("index")
        return redirect(target)
