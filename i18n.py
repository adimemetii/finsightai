def _is_valid_locale(loc: str) -> bool:
    return loc in LOCALES


def get_locale() -> str:
    """Resolve the active locale for the current request."""
    # 1) explicit ?lang= override (used by JS-less flow + tests)
    requested = (request.args.get("lang") or "").lower()
    if _is_valid_locale(requested):
        return requested
    # 2) session
    sess = session.get("lang")
    if _is_valid_locale(sess):
        return sess
    # 3) Accept-Language header
    if request.accept_languages is not None:
        for accept in request.accept_languages:
            code = (accept[0] or "").lower()[:2]
            if _is_valid_locale(code):
                return code
    return DEFAULT_LOCALE


def set_locale(loc: str) -> bool:
    """Validate and persist a locale to the session."""
    if not _is_valid_locale(loc):
        return False
    session["lang"] = loc
    return True


def t(key: str, **kwargs: Any) -> str:
    """Resolve a translation key in the active locale.

    Falls back to English for missing keys, then to the key itself, so
    partial translations never blank the UI.
    """
    loc = get_locale()
    text = MESSAGES.get(loc, {}).get(key)
    if text is None:
        text = _EN.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def catalog(locale: Optional[str] = None) -> Dict[str, str]:
    """Return the full catalog for a locale (for JS)."""
    loc = locale or get_locale()
    if not _is_valid_locale(loc):
        loc = DEFAULT_LOCALE
    # Always include English as a safety fallback for the JS layer too
    return {**_EN, **MESSAGES.get(loc, {})}


def format_currency(value: Any, locale: Optional[str] = None) -> str:
    """Format a number as currency for the active locale."""
    loc = locale or get_locale()
    if not _is_valid_locale(loc):
        loc = DEFAULT_LOCALE
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    try:
        from babel.numbers import format_currency as _bc
        return _bc(number, _LOCALE_HINTS[loc]["currency"], locale=loc)
    except Exception:
        symbol = _LOCALE_HINTS[loc]["symbol"]
        # locale-aware decimal/thousand separators
        sep = "," if loc in ("sq", "de") else "."
        if loc in ("en", "zh"):
            int_part = f"{abs(number):,.2f}".replace(",", "X").replace(".", ",").replace("X", ".")
        else:
            int_part = f"{abs(number):,.2f}"
        sign = "-" if number < 0 else ""
        return f"{sign}{symbol} {int_part}".strip()


def format_date(value: Any, locale: Optional[str] = None) -> str:
    """Format a date / datetime for the active locale."""
    loc = locale or get_locale()
    if not _is_valid_locale(loc):
        loc = DEFAULT_LOCALE
    if value is None or value == "":
        return ""
    if isinstance(value, str):
        # try parse
        try:
            value = _dt.datetime.fromisoformat(value)
        except ValueError:
            return str(value)
    if isinstance(value, _dt.date) and not isinstance(value, _dt.datetime):
        value = _dt.datetime.combine(value, _dt.time())
    try:
        from babel.dates import format_date as _bd
        return _bd(value, format="long", locale=loc)
    except Exception:
        fmt = _LOCALE_HINTS[loc]["date_fmt"]
        return value.strftime(fmt)


